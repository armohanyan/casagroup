/** Widen string literal fields to `string` so Armenian copy type-checks while preserving structure. */
type DeepStringify<T> = T extends ReadonlyArray<readonly [string, string]>
  ? readonly (readonly [string, string])[]
  : T extends ReadonlyArray<infer U>
    ? U extends Record<string, unknown>
      ? ReadonlyArray<DeepStringify<U>>
      : ReadonlyArray<string>
    : T extends string
      ? string
      : T extends number
        ? number
        : T extends Record<string, unknown>
          ? { [K in keyof T]: DeepStringify<T[K]> }
          : T;

